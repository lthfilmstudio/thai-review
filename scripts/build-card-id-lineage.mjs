#!/usr/bin/env node

import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const CARD_FIELDS = Object.freeze([
  'thai', 'karaoke', 'zh', 'type', 'note', 'audio_url', 'lesson', 'start_ms', 'end_ms',
]);
const STABLE_ID = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/;

function stableSerialize(value) {
  if (Array.isArray(value)) return `[${value.map(stableSerialize).join(',')}]`;
  if (value && typeof value === 'object') {
    return `{${Object.keys(value).sort().map(key => `${JSON.stringify(key)}:${stableSerialize(value[key])}`).join(',')}}`;
  }
  return JSON.stringify(value);
}

function sha256(value) {
  return createHash('sha256').update(value).digest('hex');
}

function smallStableHash(serialized) {
  let hash = 2166136261;
  for (const char of serialized) {
    hash ^= char.codePointAt(0);
    hash = Math.imul(hash, 16777619);
  }
  return (hash >>> 0).toString(16).padStart(8, '0');
}

function jsonBytes(value) {
  return `${JSON.stringify(value, null, 2)}\n`;
}

function trustModuleBytes(trust) {
  const { revisions, ...metadata } = trust;
  return `/* Generated by scripts/build-card-id-lineage.mjs. Do not edit by hand. */\n`
    + `const TRUSTED_REVISIONS = Object.freeze(${JSON.stringify(revisions, null, 2)});\n\n`
    + `export const TRUSTED_PRODUCTION_LINEAGE = Object.freeze({\n`
    + `${JSON.stringify(metadata, null, 2).slice(1, -1)},\n`
    + '  "revisions": TRUSTED_REVISIONS\n'
    + '});\n';
}

function cleanText(value) {
  return String(value ?? '').trim();
}

export function contentFingerprint(card = {}) {
  const payload = {};
  for (const field of CARD_FIELDS) {
    payload[field] = field === 'start_ms' || field === 'end_ms'
      ? (card[field] ?? null)
      : cleanText(card[field]);
  }
  return sha256(stableSerialize(payload));
}

function legacyAlias(lessonId, card) {
  const lesson = cleanText(lessonId);
  const thai = cleanText(card?._sourceThai || card?.thai);
  return lesson && thai ? `${lesson}:${thai}` : null;
}

function requireCatalog(data, label) {
  if (!data || !Array.isArray(data.lessons)) throw new Error(`${label} 缺少 lessons`);
  for (const lesson of data.lessons) {
    if (!cleanText(lesson?.id) || !Array.isArray(lesson?.cards)) {
      throw new Error(`${label} lesson 結構不完整`);
    }
  }
  return data;
}

function indexCurrentRows(gateManifest) {
  if (!gateManifest || !Array.isArray(gateManifest.proposals) || gateManifest.proposals.length === 0) {
    throw new Error('Gate B manifest 缺少 proposals');
  }
  const byAliasFingerprint = new Map();
  const idsByAlias = new Map();
  const allIds = new Set();
  for (const row of gateManifest.proposals) {
    const alias = cleanText(row?.legacy_alias);
    const fingerprint = cleanText(row?.content_fingerprint);
    const cardId = cleanText(row?.proposed_card_id).toLowerCase();
    if (!alias || !/^[0-9a-f]{64}$/.test(fingerprint) || !STABLE_ID.test(cardId)) {
      throw new Error('Gate B proposal identity 不完整');
    }
    if (allIds.has(cardId)) throw new Error(`Gate B card ID 重複：${cardId}`);
    allIds.add(cardId);
    const key = `${alias}\u0000${fingerprint}`;
    const matching = byAliasFingerprint.get(key) || [];
    matching.push(cardId);
    byAliasFingerprint.set(key, matching);
    const aliasIds = idsByAlias.get(alias) || [];
    aliasIds.push(cardId);
    idsByAlias.set(alias, aliasIds);
  }
  return { byAliasFingerprint, idsByAlias, allIds };
}

function indexHistoricalCatalog(data, current) {
  const cards = data.lessons.flatMap(lesson => lesson.cards.map(card => ({ lessonId: lesson.id, card })));
  const stableIdCounts = new Map();
  for (const { card } of cards) {
    const cardId = cleanText(card.card_id || card.cardId).toLowerCase();
    if (STABLE_ID.test(cardId)) stableIdCounts.set(cardId, (stableIdCounts.get(cardId) || 0) + 1);
  }
  const byAlias = new Map();
  for (const { lessonId, card } of cards) {
    const alias = legacyAlias(lessonId, card);
    if (!alias) continue;
    let candidates = [];
    let failureReason = null;
    const historicalId = cleanText(card.card_id || card.cardId).toLowerCase();
    if (historicalId) {
      const currentAliasIds = current.idsByAlias.get(alias) || [];
      if (!STABLE_ID.test(historicalId) || !current.allIds.has(historicalId)) {
        failureReason = 'invalid_lineage_identity';
      } else if ((stableIdCounts.get(historicalId) || 0) !== 1) {
        failureReason = 'duplicate_stable_card_id';
      } else if (!currentAliasIds.includes(historicalId)) {
        failureReason = 'lineage_changed';
      } else {
        candidates = [historicalId];
      }
    } else {
      candidates = current.byAliasFingerprint.get(`${alias}\u0000${contentFingerprint(card)}`) || [];
      if (candidates.length === 0) failureReason = 'missing_historical_evidence';
    }
    const rows = byAlias.get(alias) || [];
    rows.push({ candidates, failureReason });
    byAlias.set(alias, rows);
  }
  return byAlias;
}

export function buildLineageEvidence({ deploymentManifest, catalogs, gateManifest, gateManifestSha256, generatedAt }) {
  const revisions = deploymentManifest?.trustedRevisionManifest?.revisions;
  if (deploymentManifest?.kind !== 'cloudflare-pages-production-deployment-manifest-v1'
      || !Array.isArray(revisions)
      || revisions.length === 0
      || new Set(revisions).size !== revisions.length
      || !Array.isArray(catalogs)
      || catalogs.length !== revisions.length) {
    throw new Error('production deployment manifest 不完整');
  }
  const catalogByRevision = new Map(catalogs.map(row => [row.revisionId, row.data]));
  if (catalogByRevision.size !== revisions.length || revisions.some(revision => !catalogByRevision.has(revision))) {
    throw new Error('production catalog snapshots 未完整對齊 trusted revisions');
  }

  const current = indexCurrentRows(gateManifest);
  const historical = revisions.map(revision => indexHistoricalCatalog(
    requireCatalog(catalogByRevision.get(revision), revision),
    current,
  ));
  const resolvedAliases = {};
  const unresolvedReasons = {};
  const collisionAliasSet = new Set();
  for (const snapshot of historical) {
    for (const [alias, rows] of snapshot.entries()) {
      if (rows.length > 1 || rows.some(row => row.candidates.length > 1)) {
        collisionAliasSet.add(alias);
      }
    }
  }
  for (const [alias, cardIds] of current.idsByAlias.entries()) {
    if (cardIds.length > 1) collisionAliasSet.add(alias);
  }

  /* 認領規則：忽略「證據不存在」，絕不忽略「證據互相矛盾」。

     一個 revision 認不出某個 alias，有兩種完全不同的意思：

     - 沒有證據：那次部署還沒有這張卡（後來才加的課），或卡在、但內容指紋對不上。
       後者在這份 catalog 是常態——2026-08-18 那次部署把整份 karaoke 改制
       （sawatdee kha → saˇ watˇ dhī kaˋ），而 karaoke 在內容指紋裡，所以 08-18
       之前的每一份 snapshot 對每一張卡都會指紋不合。這不是「身分變了」的證據。
     - 證據矛盾：這份 revision 明確指出這個 alias 是「另一張」卡——歷史 card_id 屬於
       別的 alias（lineage_changed）、在該 snapshot 不唯一（duplicate_stable_card_id）、
       不是我們認得的 ID（invalid_lineage_identity），或 alias 在同一份裡出現多次
       （historical_collision）。這些一律 fail closed。

     舊規則把兩者都當失敗，於是 12968 個 alias 只認得出 94 個（0.7%）。分開之後是
     12324 個（95.0%）。

     ⚠️ 這條規則實際擔保什麼，要講清楚：

     20 份歷史 catalog 的 246,718 筆卡片列裡，**帶 card_id 的是 0 筆**（card_id 是
     2026-08-24 Gate B backfill 之後才有的欄位）。所以上面那三個「證據矛盾」的理由
     全都掛在 historicalId 非空那條分支上，在現有資料上**一次都觸發不了**。
     「跨 79 個 revision 沒有任何 alias 指到過第二個 card_id」這句話是真的，但它為真
     只是因為整個歷史語料裡一個 card_id 觀測值都沒有——它證明不了身分穩定性。

     真正擋住「把進度接到錯的卡」的不是歷史，是這件事：alias 在**現行 catalog**
     解析到恰好一張卡時，根本沒有第二張卡可以認錯——candidates 只從以 alias 為鍵的
     索引取，而 alias 在現行 catalog 不唯一就會先進 collisionAliasSet。這套機制只能
     「拒絕」，不能「改指向」。644 筆未認領正好就是有第二個候選的那些。

     歷史 snapshot 剩下的作用是內容穩定性：這個 alias 至少在一份 production 部署裡
     以完全相同的內容出現過。那三個矛盾理由留著是為了未來 catalog 帶 card_id 之後
     能生效，現在是死的。 */
  for (const alias of [...current.idsByAlias.keys()].sort()) {
    let reason = collisionAliasSet.has(alias) ? 'historical_collision' : null;
    const ids = new Set();
    for (const snapshot of historical) {
      const rows = snapshot.get(alias);
      if (!rows || rows.length === 0) continue;
      if (rows.length !== 1) {
        reason = 'historical_collision';
        continue;
      }
      const [row] = rows;
      if (row.failureReason) {
        if (row.failureReason !== 'missing_historical_evidence') reason = row.failureReason;
        continue;
      }
      if (row.candidates.length !== 1) {
        reason = 'historical_collision';
        continue;
      }
      ids.add(row.candidates[0]);
    }
    if (!reason && ids.size > 1) reason = 'lineage_changed';
    if (!reason && ids.size === 0) reason = 'missing_historical_evidence';
    if (reason) {
      unresolvedReasons[alias] = reason;
    } else {
      resolvedAliases[alias] = [...ids][0];
    }
  }

  const collisionAliases = [...collisionAliasSet].sort();
  const canonicalCardIds = [...new Set(Object.values(resolvedAliases))].sort();
  const summary = {
    deploymentCount: revisions.length,
    currentCardCount: current.allIds.size,
    currentAliasCount: current.idsByAlias.size,
    resolvedAliasCount: Object.keys(resolvedAliases).length,
    unresolvedAliasCount: Object.keys(unresolvedReasons).length,
    historicalCollisionAliasCount: collisionAliases.length,
  };
  if (summary.resolvedAliasCount + summary.unresolvedAliasCount !== summary.currentAliasCount) {
    throw new Error('lineage alias conservation failed');
  }
  const evidenceCore = {
    kind: 'production-lineage-evidence-v2',
    schemaVersion: 2,
    completeness: 'complete',
    generatedAt,
    expectedRevisions: [...revisions],
    source: {
      deploymentManifestSha256: deploymentManifest.manifestSha256,
      gateManifestSha256,
      projectName: deploymentManifest.projectName,
      environment: deploymentManifest.environment,
    },
    resolvedAliases,
    unresolvedReasons,
    collisionAliases,
    canonicalCardIds,
    summary,
  };
  return {
    ...evidenceCore,
    evidenceId: `production-lineage-evidence-v2:fnv1a32:${smallStableHash(stableSerialize(evidenceCore))}`,
  };
}

function parseArgs(argv) {
  const args = {};
  for (let index = 0; index < argv.length; index += 2) {
    const flag = argv[index];
    const value = argv[index + 1];
    if (!flag?.startsWith('--') || value === undefined) throw new Error(`invalid argument: ${flag || ''}`);
    args[flag.slice(2)] = value;
  }
  return args;
}

function oauthToken(configPath) {
  const match = readFileSync(configPath, 'utf8').match(/^oauth_token = "([^"]+)"/m);
  if (!match) throw new Error('Wrangler OAuth token unavailable');
  return match[1];
}

async function fetchJson(url, options = {}, timeoutMs = 20_000) {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), timeoutMs);
  try {
    const response = await fetch(url, { ...options, signal: controller.signal });
    const raw = Buffer.from(await response.arrayBuffer());
    if (!response.ok) throw new Error(`${url} HTTP ${response.status}`);
    return { data: JSON.parse(raw.toString('utf8')), raw };
  } finally {
    clearTimeout(timer);
  }
}

async function mapLimit(items, limit, mapper) {
  const results = new Array(items.length);
  let cursor = 0;
  async function worker() {
    while (cursor < items.length) {
      const index = cursor;
      cursor += 1;
      results[index] = await mapper(items[index], index);
    }
  }
  await Promise.all(Array.from({ length: Math.min(limit, items.length) }, worker));
  return results;
}

async function listDeployments({ accountId, projectName, token }) {
  const endpoint = `https://api.cloudflare.com/client/v4/accounts/${accountId}/pages/projects/${projectName}/deployments`;
  const pageSize = 25;
  const readPage = async page => {
    const url = new URL(endpoint);
    url.search = new URLSearchParams({ env: 'production', page: String(page), per_page: String(pageSize) });
    const { data } = await fetchJson(url, { headers: { Authorization: `Bearer ${token}` } });
    if (data?.success !== true || !Array.isArray(data.result)) throw new Error(`Cloudflare deployment page ${page} failed`);
    return data;
  };
  const first = await readPage(1);
  const totalPages = first.result_info?.total_pages;
  const totalCount = first.result_info?.total_count;
  if (!Number.isInteger(totalPages) || !Number.isInteger(totalCount) || totalPages < 1 || totalCount < 1) {
    throw new Error('Cloudflare pagination metadata unavailable');
  }
  const rows = [...first.result];
  for (let page = 2; page <= totalPages; page += 1) rows.push(...(await readPage(page)).result);
  const recheck = await readPage(1);
  if (recheck.result_info?.total_count !== totalCount
      || stableSerialize(recheck.result.map(row => row.id)) !== stableSerialize(first.result.map(row => row.id))
      || rows.length !== totalCount
      || new Set(rows.map(row => row.id)).size !== rows.length) {
    throw new Error('Cloudflare deployment list changed during pagination');
  }
  return { rows: rows.reverse(), totalPages, totalCount, pageSize };
}

function gitCatalog(revision) {
  const raw = execFileSync('git', ['show', `${revision}:data.json`], {
    maxBuffer: 100 * 1024 * 1024,
  });
  return requireCatalog(JSON.parse(raw.toString('utf8')), revision);
}

function emitEvidence({ evidence, deploymentManifest, args, extra = {} }) {
  const lineageOutput = resolve(args['lineage-output']);
  mkdirSync(dirname(lineageOutput), { recursive: true });
  const evidenceBytes = jsonBytes(evidence);
  writeFileSync(lineageOutput, evidenceBytes);
  const trust = {
    kind: 'trusted-lineage-revision-manifest-v1',
    projectName: deploymentManifest.projectName,
    environment: deploymentManifest.environment,
    sourceManifestSha256: deploymentManifest.manifestSha256,
    evidenceId: evidence.evidenceId,
    // evidenceId 是 32-bit FNV，只防意外損壞。真正的完整性綁定是這支 SHA-256：
    // runtime 對「實際取回的 bytes」比對，格式降級與雜湊碰撞都過不了。
    evidenceSha256: sha256(evidenceBytes),
    revisions: deploymentManifest.trustedRevisionManifest.revisions,
  };
  const trustOutput = resolve(args['trust-output']);
  mkdirSync(dirname(trustOutput), { recursive: true });
  writeFileSync(trustOutput, trustModuleBytes(trust));
  console.log(JSON.stringify({ ...extra, ...evidence.summary, lineageOutput, trustOutput }));
}

/* 離線重建：不打 Cloudflare API，改用已記錄的 deployment manifest 加 git 裡的 data.json。
   每一份重建出來的 catalog 都要對得上 manifest 記的 catalogSha256——那是離線模式唯一的
   完整性依據，對不上就中止。用在「trusted revision 清單沒變、只是重跑認領規則」的場合；
   要納入新的 production 部署仍然得走線上模式。 */
function offlineCatalogs(deploymentManifest) {
  const revisions = deploymentManifest?.trustedRevisionManifest?.revisions;
  const deployments = deploymentManifest?.deployments;
  if (!Array.isArray(revisions) || !Array.isArray(deployments) || revisions.length !== deployments.length) {
    throw new Error('offline deployment manifest 不完整');
  }
  const { manifestSha256, ...core } = deploymentManifest;
  if (sha256(jsonBytes(core)) !== manifestSha256) {
    throw new Error('offline deployment manifest 的 manifestSha256 對不上內容');
  }
  const cache = new Map();
  return deployments.map((row, index) => {
    if (row.revisionId !== revisions[index]) throw new Error(`revision 順序不一致：${row.revisionId}`);
    const commit = row.matchingCatalogCommit;
    if (!/^[0-9a-f]{40}$/.test(commit || '')) throw new Error(`${row.revisionId} 缺少 catalog commit`);
    if (!cache.has(commit)) cache.set(commit, gitCatalog(commit));
    const data = cache.get(commit);
    const digest = sha256(stableSerialize({ lessons: data.lessons, dialogues: data.dialogues || [] }));
    if (digest !== row.catalogSha256) {
      throw new Error(`${row.revisionId} 的 git snapshot 與記錄的 catalogSha256 不符`);
    }
    return { revisionId: row.revisionId, data };
  });
}

function runOffline(args) {
  const required = [
    'offline-deployment-manifest', 'gate-manifest', 'lineage-output', 'trust-output', 'generated-at',
  ];
  for (const name of required) if (!args[name]) throw new Error(`missing --${name}`);
  const deploymentManifest = JSON.parse(readFileSync(resolve(args['offline-deployment-manifest']), 'utf8'));
  const gateBytes = readFileSync(resolve(args['gate-manifest']));
  const catalogs = offlineCatalogs(deploymentManifest);
  const evidence = buildLineageEvidence({
    deploymentManifest,
    catalogs,
    gateManifest: JSON.parse(gateBytes.toString('utf8')),
    gateManifestSha256: sha256(gateBytes),
    generatedAt: args['generated-at'],
  });
  emitEvidence({
    evidence,
    deploymentManifest,
    args,
    extra: { mode: 'offline', distinctCatalogCount: new Set(catalogs.map(row => row.data)).size },
  });
}

async function run() {
  const args = parseArgs(process.argv.slice(2));
  if (args['offline-deployment-manifest']) return runOffline(args);
  const required = [
    'account-id', 'project-name', 'wrangler-config', 'gate-manifest',
    'deployment-output', 'lineage-output', 'trust-output', 'generated-at',
  ];
  for (const name of required) if (!args[name]) throw new Error(`missing --${name}`);
  const token = oauthToken(resolve(args['wrangler-config']));
  const gateManifestPath = resolve(args['gate-manifest']);
  const gateBytes = readFileSync(gateManifestPath);
  const gateManifest = JSON.parse(gateBytes.toString('utf8'));
  const listed = await listDeployments({
    accountId: args['account-id'],
    projectName: args['project-name'],
    token,
  });
  if (listed.rows.some(row => row.environment !== 'production')) {
    throw new Error('Cloudflare deployment list 混入非 production row');
  }

  const sourceRevisions = [...new Set(listed.rows.map(row => row.deployment_trigger?.metadata?.commit_hash))];
  if (sourceRevisions.some(revision => !/^[0-9a-f]{40}$/.test(revision || ''))) {
    throw new Error('deployment source commit 不完整');
  }
  const gitCatalogSources = new Map();
  for (const revision of sourceRevisions) {
    const data = gitCatalog(revision);
    const digest = sha256(stableSerialize({ lessons: data.lessons, dialogues: data.dialogues || [] }));
    const candidates = gitCatalogSources.get(digest) || [];
    candidates.push(revision);
    gitCatalogSources.set(digest, candidates);
  }

  const collected = await mapLimit(listed.rows, 8, async (row, index) => {
    const { data, raw } = await fetchJson(new URL('/data.json', row.url));
    requireCatalog(data, row.id);
    const catalogSha256 = sha256(stableSerialize({ lessons: data.lessons, dialogues: data.dialogues || [] }));
    const matchingGitRevisions = gitCatalogSources.get(catalogSha256) || [];
    if (matchingGitRevisions.length === 0) throw new Error(`${row.id} production catalog 無可保存的 Git snapshot`);
    const dataSha256 = sha256(raw);
    const revisionId = `cloudflare-pages-production:${String(index + 1).padStart(3, '0')}:data:${dataSha256}`;
    return {
      deployment: {
      revisionId,
      createdAt: row.created_on,
      sourceCommit: row.deployment_trigger.metadata.commit_hash,
      matchingCatalogCommit: matchingGitRevisions[0],
      sourceCommitMatchesCatalog: matchingGitRevisions.includes(row.deployment_trigger.metadata.commit_hash),
      dataSha256,
      catalogSha256,
      cardCount: data.lessons.flatMap(lesson => lesson.cards).length,
      },
      catalog: { revisionId, data },
    };
  });
  const deployments = collected.map(row => row.deployment);
  const catalogs = collected.map(row => row.catalog);

  const deploymentCore = {
    kind: 'cloudflare-pages-production-deployment-manifest-v1',
    schemaVersion: 1,
    generatedAt: args['generated-at'],
    projectName: args['project-name'],
    environment: 'production',
    enumeration: {
      pageSize: listed.pageSize,
      pageCount: listed.totalPages,
      totalCount: listed.totalCount,
    },
    deployments,
    trustedRevisionManifest: {
      kind: 'trusted-lineage-revision-manifest-v1',
      revisions: deployments.map(row => row.revisionId),
    },
  };
  const deploymentWithoutHash = jsonBytes(deploymentCore);
  const deploymentManifest = { ...deploymentCore, manifestSha256: sha256(deploymentWithoutHash) };
  const deploymentOutput = resolve(args['deployment-output']);
  mkdirSync(dirname(deploymentOutput), { recursive: true });
  writeFileSync(deploymentOutput, jsonBytes(deploymentManifest));

  const evidence = buildLineageEvidence({
    deploymentManifest,
    catalogs,
    gateManifest,
    gateManifestSha256: sha256(gateBytes),
    generatedAt: args['generated-at'],
  });
  emitEvidence({
    evidence,
    deploymentManifest,
    args,
    extra: {
      mode: 'online',
      sourceMismatchCount: deployments.filter(row => !row.sourceCommitMatchesCatalog).length,
      deploymentOutput,
    },
  });
}

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  run().catch(error => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
